-- 009: bases consultadas na API do Portal da Transparência pelo modo exploration (decisão 0014).

-- 'sample': os jobs filtram a amostra publicada (payments). 'portal': o worker busca o recorte na API do Portal.
ALTER TABLE sources ADD COLUMN kind text NOT NULL DEFAULT 'sample' CHECK (kind IN ('sample', 'portal'));

-- Andamento informado pelo worker enquanto o job roda (ex.: requisições feitas e registros baixados da API).
ALTER TABLE jobs ADD COLUMN progress jsonb;

-- As execuções sobre bases do Portal não partem da amostra publicada.
ALTER TABLE runs ALTER COLUMN train_sample_id DROP NOT NULL;
ALTER TABLE runs ADD CONSTRAINT runs_train_sample_check CHECK (mode = 'exploration' OR train_sample_id IS NOT NULL);

-- Registros baixados da API para um job. Apagados com o job (retenção do modo exploration).
-- BY DEFAULT: o worker reserva os ids na sequência e grava os registros e os escores por COPY.
CREATE TABLE portal_records (
    id        bigint             GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id    uuid               NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    "values"  jsonb              NOT NULL,  -- colunas de exibição (sources.display_columns), sem dados de pessoa física
    features  double precision[] NOT NULL   -- na ordem de sources.feature_columns
);

CREATE INDEX portal_records_job_idx ON portal_records (job_id);

-- Escores das execuções sobre registros do Portal (run_scores referencia payments).
CREATE TABLE portal_scores (
    run_id            integer          NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
    record_id         bigint           NOT NULL REFERENCES portal_records (id) ON DELETE CASCADE,
    raw_score         double precision NOT NULL,
    normalized_score  real             NOT NULL CHECK (normalized_score > 0 AND normalized_score <= 1),
    PRIMARY KEY (run_id, record_id)
);

ALTER TABLE portal_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE portal_scores  ENABLE ROW LEVEL SECURITY;
